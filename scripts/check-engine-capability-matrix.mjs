import fs from "node:fs";
import path from "node:path";
import process from "node:process";

const ROOT = process.cwd();
const FIXTURE_PATH = path.join(
  ROOT,
  "openspec/specs/engine-capability-matrix/fixtures/matrix.json",
);
const TS_GENERATED_PATH = path.join(
  ROOT,
  "src/features/engine/generated/engineCapabilityMatrix.generated.ts",
);
const RUST_GENERATED_PATH = path.join(
  ROOT,
  "src-tauri/src/engine/capability_matrix.generated.rs",
);
const RUST_PROJECTION_PATH = path.join(ROOT, "src-tauri/src/engine/capability_matrix.rs");
const WRITE_MODE = process.argv.includes("--write");

const ENGINE_VARIANTS = {
  claude: "Claude",
  codex: "Codex",
  gemini: "Gemini",
  grok: "Grok",
  opencode: "OpenCode",
  kimi: "Kimi",
  pi: "Pi",
  omp: "Omp",
  dsh: "Dsh",
  qoder: "Qoder",
};
const VALID_STATE = new Set(["supported", "compat-input", "unsupported", "unknown"]);
const VALID_DOMAIN = new Set([
  "streaming",
  "tool",
  "hook",
  "memory",
  "subagent",
  "cost",
  "session",
  "image",
  "compaction",
  "reasoning",
  "collaboration",
  "input",
  "rpc",
]);

function readText(filePath) {
  return fs.readFileSync(filePath, "utf8");
}

function fail(message) {
  throw new Error(`[engine-capability-matrix] ${message}`);
}

function validateFixture(fixture) {
  const capabilities = fixture.capabilities ?? [];
  const engines = fixture.engines ?? {};
  if (!Array.isArray(capabilities) || capabilities.length === 0) {
    fail("fixture must define non-empty capabilities");
  }
  if (new Set(capabilities).size !== capabilities.length) {
    fail("fixture capability keys must be unique");
  }
  for (const capability of capabilities) {
    if (!/^[a-z][a-z0-9-]*\.[a-z][a-z0-9-]*(\.[a-z][a-z0-9-]*)?$/.test(capability)) {
      fail(`invalid capability key "${capability}"`);
    }
    const domain = capability.split(".")[0];
    if (!VALID_DOMAIN.has(domain)) {
      fail(`invalid capability domain "${domain}" in "${capability}"`);
    }
  }
  for (const engine of Object.keys(ENGINE_VARIANTS)) {
    const table = engines[engine];
    if (!table) {
      fail(`fixture missing engine "${engine}"`);
    }
    for (const capability of capabilities) {
      const state = table[capability];
      if (!VALID_STATE.has(state)) {
        fail(`invalid state at engines.${engine}.${capability}: ${String(state)}`);
      }
    }
    const extraCapabilities = Object.keys(table).filter(
      (capability) => !capabilities.includes(capability),
    );
    if (extraCapabilities.length > 0) {
      fail(`extra capability at engines.${engine}.${extraCapabilities[0]}`);
    }
  }
  const extraEngines = Object.keys(engines).filter((engine) => !ENGINE_VARIANTS[engine]);
  if (extraEngines.length > 0) {
    fail(`unexpected engine "${extraEngines[0]}"`);
  }
}

function renderTypeScript(fixture) {
  const keys = fixture.capabilities.map((key) => `  ${JSON.stringify(key)},`).join("\n");
  return `// Generated by scripts/check-engine-capability-matrix.mjs --write. Do not edit.
import type { EngineType } from "../../../types";

export const GENERATED_ENGINE_CAPABILITY_KEYS = [
${keys}
] as const;

export type GeneratedEngineCapabilityKey =
  (typeof GENERATED_ENGINE_CAPABILITY_KEYS)[number];
export type GeneratedEngineCapabilityState =
  | "supported"
  | "compat-input"
  | "unsupported"
  | "unknown";

export const GENERATED_ENGINE_CAPABILITY_MATRIX: Readonly<
  Record<EngineType, Readonly<Record<GeneratedEngineCapabilityKey, GeneratedEngineCapabilityState>>>
> = ${JSON.stringify(fixture.engines, null, 2)} as const;
`;
}

function renderRust(fixture) {
  const keys = fixture.capabilities.map((key) => `    ${JSON.stringify(key)},`).join("\n");
  const engineMatches = Object.entries(ENGINE_VARIANTS)
    .map(([engine, variant]) => {
      const capabilityMatches = fixture.capabilities
        .map(
          (capability) =>
            `            ${JSON.stringify(capability)} => ${JSON.stringify(
              fixture.engines[engine][capability],
            )},`,
        )
        .join("\n");
      return `        EngineType::${variant} => match capability {
${capabilityMatches}
            _ => "unknown",
        },`;
    })
    .join("\n");
  return `// Generated by scripts/check-engine-capability-matrix.mjs --write. Do not edit.

pub const SPEC_CAPABILITY_KEYS: [&str; ${fixture.capabilities.length}] = [
${keys}
];

pub fn spec_capability_state(engine_type: EngineType, capability: &str) -> &'static str {
    match engine_type {
${engineMatches}
    }
}
`;
}

function syncGeneratedArtifact(filePath, expected) {
  if (WRITE_MODE) {
    fs.mkdirSync(path.dirname(filePath), { recursive: true });
    fs.writeFileSync(filePath, expected);
    return;
  }
  if (!fs.existsSync(filePath)) {
    fail(`generated artifact missing: ${path.relative(ROOT, filePath)}`);
  }
  if (readText(filePath) !== expected) {
    fail(
      `generated artifact drift: ${path.relative(
        ROOT,
        filePath,
      )}; run "node scripts/check-engine-capability-matrix.mjs --write"`,
    );
  }
}

try {
  const fixture = JSON.parse(readText(FIXTURE_PATH));
  validateFixture(fixture);
  syncGeneratedArtifact(TS_GENERATED_PATH, renderTypeScript(fixture));
  syncGeneratedArtifact(RUST_GENERATED_PATH, renderRust(fixture));

  const rustProjectionSource = readText(RUST_PROJECTION_PATH);
  for (const capability of fixture.capabilities) {
    if (!rustProjectionSource.includes(JSON.stringify(capability))) {
      fail(`Rust runtime projection missing capability "${capability}"`);
    }
  }

  const bridgeAdapterSource = readText(
    path.join(ROOT, "src/features/governance/evidence/harnessEvidenceAdapters.ts"),
  );
  for (const token of [
    "createCapabilityGovernanceEvidence",
    "EngineCapabilityRuntimeStatus",
    'source: "engine-capability-matrix"',
    "specState",
    "runtimeState",
    "available",
  ]) {
    if (!bridgeAdapterSource.includes(token)) {
      fail(`harnessEvidenceAdapters missing capability evidence token "${token}"`);
    }
  }

  console.log(
    `[engine-capability-matrix] ${WRITE_MODE ? "generated" : "ok"} (${fixture.capabilities.length} capabilities)`,
  );
} catch (error) {
  console.error(error instanceof Error ? error.message : String(error));
  process.exitCode = 1;
}
